// controllers/report.controller.js
const PDFDocument = require('pdfkit');
const { getReportData } = require('../models/Report.model');
const { registerAction } = require('../models/log.model');

// Hardcoded session - Manager = Francisco Rafael
const HARDCODED_MANAGER = {
  Id_Usuario: 1,
  Nombre_Completo: 'Francisco Rafael Arreola Corona',
  rol: 'manager'
};

const exportPDF = async (req, res) => {
  const { idEquipo, idProyecto, fechaInicio, fechaFin } = req.query;

  // Validate required parameters
  if (!idEquipo || !idProyecto || !fechaInicio || !fechaFin) {
    return res.status(400).json({
      error: 'Missing parameters: idEquipo, idProyecto, fechaInicio, fechaFin'
    });
  }

  // Log START of operation
  await registerAction(
    idProyecto,
    HARDCODED_MANAGER.Id_Usuario,
    `START PDF export - Team: ${idEquipo} Period: ${fechaInicio} to ${fechaFin}`
  ).catch(() => {});

  let data;
  try {
    data = await getReportData(idEquipo, idProyecto, fechaInicio, fechaFin);
  } catch (err) {
    console.error('Error fetching report data:', err);

    await registerAction(
      idProyecto,
      HARDCODED_MANAGER.Id_Usuario,
      `ERROR PDF export - ${err.message}`
    ).catch(() => {});

    return res.status(500).json({ error: 'Error fetching report data.' });
  }

  // Validate data exists
  if (!data.equipo || !data.proyecto) {
    return res.status(404).json({
      error: 'No data available to generate the report.'
    });
  }

  // ── Generate PDF ──────────────────────────────────────────
  try {
    const doc = new PDFDocument({ margin: 50 });

    // Headers for browser download
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename="report_${data.equipo.Nombre_Equipo}_${fechaInicio}_${fechaFin}.pdf"`
    );

    doc.pipe(res);

    // ── HEADER ──
    doc
      .fontSize(20)
      .fillColor('#E84C1E')
      .text('Weekly Report — Change.org', { align: 'center' });

    doc.moveDown(0.5);
    doc
      .fontSize(14)
      .fillColor('#000000')
      .text(`Team: ${data.equipo.Nombre_Equipo}`, { align: 'center' });

    doc
      .fontSize(11)
      .fillColor('#555555')
      .text(`Project: ${data.proyecto.Nombre_Proyecto}`, { align: 'center' });

    doc
      .fontSize(10)
      .text(`Period: ${fechaInicio} — ${fechaFin}`, { align: 'center' });

    doc
      .fontSize(10)
      .text(`Generated by: ${HARDCODED_MANAGER.Nombre_Completo}`, { align: 'center' });

    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke('#E84C1E');
    doc.moveDown();

    // ── GENERAL METRICS ──
    doc.fontSize(13).fillColor('#E84C1E').text('General Metrics');
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor('#000000');
    doc.text(`• Total active members: ${data.miembros.length}`);
    doc.text(`• Total log entries: ${data.bitacoras.length}`);
    doc.text(`• Total achievements recorded: ${data.logros.length}`);
    doc.text(`• Total active blockers: ${data.bloqueos.length}`);
    doc.text(`• Total project goals: ${data.metas.length}`);

    doc.moveDown();

    // ── TEAM MEMBERS ──
    doc.fontSize(13).fillColor('#E84C1E').text('Team Members');
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor('#000000');

    if (data.miembros.length === 0) {
      doc.text('No members registered in this team.');
    } else {
      data.miembros.forEach((m) => {
        doc.text(`• ${m.Nombre_Completo} — ${m.Correo_Institucional}`);
      });
    }

    doc.moveDown();

    // ── ACHIEVEMENTS ──
    doc.fontSize(13).fillColor('#E84C1E').text('Achievements');
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor('#000000');

    if (data.logros.length === 0) {
      doc.text('No achievements recorded in this period.');
    } else {
      data.logros.forEach((l) => {
        doc.text(`• [${l.Fecha_Creacion}] ${l.Nombre_Completo}: ${l.Descripcion}`);
      });
    }

    doc.moveDown();

    // ── BLOCKERS ──
    doc.fontSize(13).fillColor('#E84C1E').text('Current Blockers');
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor('#000000');

    if (data.bloqueos.length === 0) {
      doc.text('No blockers recorded in this period.');
    } else {
      data.bloqueos.forEach((b) => {
        doc.text(
          `• ${b.Nombre_Completo} — ${b.Descripcion_Bloqueo} [${b.Estado_Resolucion || 'No status'}]`
        );
      });
    }

    doc.moveDown();

    // ── GOALS ──
    doc.fontSize(13).fillColor('#E84C1E').text('Project Goals');
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor('#000000');

    if (data.metas.length === 0) {
      doc.text('No goals registered for this project.');
    } else {
      data.metas.forEach((m) => {
        doc.text(`• ${m.Nombre_Meta}`);
        if (m.Descripcion_Objetivo) {
          doc
            .fontSize(9)
            .fillColor('#555555')
            .text(`  ${m.Descripcion_Objetivo}`, { indent: 10 });
          doc.fontSize(10).fillColor('#000000');
        }
      });
    }

    doc.moveDown();

    // ── LOG ENTRIES ──
    doc.fontSize(13).fillColor('#E84C1E').text('Log Entries');
    doc.moveDown(0.3);
    doc.fontSize(10).fillColor('#000000');

    if (data.bitacoras.length === 0) {
      doc.text('No log entries in this period.');
    } else {
      data.bitacoras.forEach((b) => {
        doc.text(`• [${b.Fecha_Registro}] ${b.Nombre_Completo}`);
        if (b.Avance_Realizado) {
          doc
            .fontSize(9)
            .fillColor('#555555')
            .text(`  Completed: ${b.Avance_Realizado}`, { indent: 10 });
        }
        if (b.Avance_Planeado) {
          doc
            .fontSize(9)
            .fillColor('#555555')
            .text(`  Planned: ${b.Avance_Planeado}`, { indent: 10 });
        }
        if (b.Porcentaje_Progreso) {
          doc
            .fontSize(9)
            .fillColor('#555555')
            .text(`  Progress: ${b.Porcentaje_Progreso}%`, { indent: 10 });
        }
        doc.fontSize(10).fillColor('#000000');
        doc.moveDown(0.3);
      });
    }

    // ── FOOTER ──
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke('#E84C1E');
    doc.moveDown(0.5);
    doc
      .fontSize(9)
      .fillColor('#999999')
      .text(`Report generated on ${new Date().toLocaleDateString('en-US')}`, {
        align: 'center'
      });

    doc.end();

    // Log SUCCESS
   await registerAction(
      idProyecto,
      HARDCODED_MANAGER.Id_Usuario,
      `END successful PDF export - Team: ${idEquipo} Period: ${fechaInicio} to ${fechaFin}`
    ).catch(() => {});

  } catch (err) {
    console.error('Error generating PDF:', err);

    await registerAction(
      idProyecto,
      HARDCODED_MANAGER.Id_Usuario,
      `ERROR PDF generation - ${err.message}`
    ).catch(() => {});

    if (!res.headersSent) {
      return res.status(500).json({ error: 'Error generating PDF file.' });
    }
  }
};

module.exports = { exportPDF };